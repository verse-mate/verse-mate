  async getReportSummaries(
    coachId: string,
    opts: { limit?: number; offset?: number } = {},
    audience: "leader" | "admin" = "leader",
  ): Promise<{
    items: Record<string, unknown>[];
    total: number;
    streakWeeks: number;
    quarterSessions: number;
  }> {
    const includeHeld = audience === "admin";
    const record = await this.resolveById(coachId);
    const bundled = record?.reports ?? [];
    const backfilled =
      bundled.length === 0 ||
      (record !== null && (await this.isBackfilled(record)));
    const dates = CoachService.withBundle(
      await this.reportsRepository.listSessionDates(coachId, {
        includeHeld: false,
      }),
      bundled.map((r) => ({ id: r.id, date: r.date })),
      backfilled,
    ).map((r) => r.date);
    const aggregates = {
      streakWeeks: CoachService.streakWeeks(dates),
      quarterSessions: CoachService.quarterSessions(dates),
    };
    const page = backfilled
      ? await this.storedSummaryPage(coachId, opts, includeHeld)
      : await this.mergedSummaryPage(coachId, bundled, opts, includeHeld);
    const items =
      audience === "admin"
        ? await this.withRecordingFields(coachId, page.items)
        : page.items;
    return { items, total: page.total, ...aggregates };
  }

  private async storedSummaryPage(
    coachId: string,
    opts: { limit?: number; offset?: number },
    includeHeld: boolean,
  ): Promise<{ items: Record<string, unknown>[]; total: number }> {
    const total = await this.reportsRepository.countForCoach(coachId, {
      includeHeld,
    });
    if (total === 0) return { items: [], total: 0 };
    const rows = await this.reportsRepository.listSummaries(coachId, {
      ...opts,
      includeHeld,
    });
    return {
      items: rows.map((r) => ({
        ...rowToSummary({ id: r.id, session_date: r.date, summary: r.summary }),
        ...(includeHeld ? { held: r.held === true } : {}),
      })),
      total,
    };
  }

  private async mergedSummaryPage(
    coachId: string,
    bundled: CoachReport[],
    opts: { limit?: number; offset?: number },
    includeHeld: boolean,
  ): Promise<{ items: Record<string, unknown>[]; total: number }> {
    const stored = (
      await this.reportsRepository.listFullReports(coachId, { includeHeld })
    ).map((r) => ({
      ...rowToSummary({ id: r.id, session_date: r.date, summary: r.summary }),
      ...(includeHeld ? { held: r.held === true } : {}),
    }));
    const all = CoachService.withBundle(
      stored,
      bundled.map((r) => ({
        id: r.id,
        date: r.date,
        dateLabel: r.dateLabel,
        session: r.session,
        topic: r.topic,
        score: r.score,
        status: r.status,
        statusEmoji: r.statusEmoji,
        pdfUrl: r.pdfUrl,
        ...(includeHeld ? { held: false } : {}),
      })) as Record<string, unknown>[],
      false,
    );
    const limit = Number.isFinite(Number(opts.limit))
      ? Math.min(Math.max(Math.trunc(Number(opts.limit)), 1), 100)
      : 25;
    const offset = Number.isFinite(Number(opts.offset))
      ? Math.max(Math.trunc(Number(opts.offset)), 0)
      : 0;
    return { items: all.slice(offset, offset + limit), total: all.length };
  }

  private async withRecordingFields(
    coachId: string,
    items: Record<string, unknown>[],
  ): Promise<Record<string, unknown>[]> {
    if (items.length === 0) return items;
    const [links, media] = await Promise.all([
      this.coachRepository.getRecordingLinksForCoach(coachId),
      this.describeRetainedMedia(
        coachId,
        items.map((i) => String(i.id)),
      ),
    ]);
    return items.map((i) => {
      const id = String(i.id);
      return {
        ...i,
        hasRetainedRecording: media.get(id)?.hasRetainedRecording ?? false,
        attachedRecordingUrl: links[id] ? links[id] : null,
      };
    });
  }

  private static weekOf(iso: string): number {
    const [y, m, d] = iso.split("-").map(Number);
    const day = new Date(Date.UTC(y, (m || 1) - 1, d || 1));
    return day.getTime() - ((day.getUTCDay() + 6) % 7) * CoachService.DAY_MS;
  }

  private static readonly DAY_MS = 24 * 60 * 60 * 1000;

  static streakWeeks(dates: string[]): number {
    if (dates.length === 0) return 0;
    const weeks = new Set(dates.map(CoachService.weekOf));
    let cursor = Math.max(...weeks);
    let streak = 0;
    while (weeks.has(cursor)) {
      streak += 1;
      cursor -= 7 * CoachService.DAY_MS;
    }
    return streak;
  }

  static quarterSessions(dates: string[]): number {
    if (dates.length === 0) return 0;
    const days = dates.map((d) => {
      const [y, m, day] = d.split("-").map(Number);
      return Date.UTC(y, (m || 1) - 1, day || 1);
    });
    const cutoff = Math.max(...days) - 91 * CoachService.DAY_MS;
    return days.filter((t) => t >= cutoff).length;
  }

  /**
   * One session's full content by immutable OR legacy id, SCOPED to the coach
   * that owns it. Null when the id names nothing for that coach, so a leader
   * can never read another leader's report, and an unknown id reports
   * not-found rather than silently showing a different session.
   */
  async getReportDetail(
    coachId: string,
    reportId: string,
    audience: "leader" | "admin" = "leader",
  ): Promise<CoachReport | null> {
    const row = await this.reportsRepository.getDetail(coachId, reportId, {
      includeHeld: audience === "admin",
    });
    if (row) {
      const report = rowToReport({
        id: row.id,
        session_date: row.date,
        summary: row.summary,
        metrics: row.metrics,
        body: row.body,
      }) as unknown as CoachReport;
      const [overlaid] = await this.overlayReports(coachId, [report]);
      const resolved = overlaid ?? report;
      // Detail-only: WHETHER we hold a recording, never where. The address is
      // minted separately, one session at a time (task 4.5).
      const media = (await this.describeRetainedMedia(coachId, [row.id])).get(
        row.id,
      );
      return {
        ...resolved,
        hasRetainedRecording: media?.hasRetainedRecording ?? false,
      } as CoachReport;
    }
    // Migration-gate: the bundle still answers for reports not yet backfilled —
    // scoped to THIS coach only, never a global search across every leader.
    const bundled = this.bundle.coaches.find((c) => c.id === coachId);
    const found = bundled?.reports.find((r) => r.id === reportId);
    if (found) {
      const [overlaid] = await this.overlayReports(coachId, [found]);
      return overlaid ?? found;
    }
    return null;
  }

