  async listPipelineFailures(
    page: { limit?: number; offset?: number } = {},
  ): Promise<{
    total: number;
    sessions: Array<{
      sourceSessionId: string;
      coachId: string | null;
      title: string;
      sessionDate: string;
      sessionStartedAt: Date | null;
      state: string;
      attempts: number;
      reportId: string | null;
      reason: string | null;
      holdKind: HoldKind | null;
      coldRecall?: string[];
      action: "release" | "requeue" | "attribute" | null;
      parallelRun: boolean;
      updatedAt: Date;
    }>;
  }> {
    const limit = Math.min(
      Math.max(1, page.limit ?? PIPELINE_FAILURES_PAGE),
      PIPELINE_FAILURES_MAX,
    );
    const offset = Math.max(0, page.offset ?? 0);
    const rows = await this.db
      .getOrCreateConnection()
      .selectFrom("coach_intake_sessions")
      .select([
        "source_session_id",
        "coach_id",
        "title",
        "state",
        "retry_count",
        "report_id",
        "hold_reason",
        "hold_kind",
        "release_required",
        "parallel_run",
        "session_started_at",
        "updated_at",
        "leader_cue",
      ])
      .select(sql<string>`to_char(session_date, 'YYYY-MM-DD')`.as("date"))
      .select(SKIPPED_LEADER_ADDRESS.as("skipped_leader"))
      .select(SKIPPED_LEADER_IS_GROUP.as("skipped_group"))
      .select(COLD_RECALL_FEEDBACK.as("cold_recall_feedback"))
      .select(sql<string>`count(*) OVER ()`.as("total"))
      .where(stuck)
      .orderBy("updated_at", "desc")
      .orderBy("source_session_id")
      .limit(limit)
      .offset(offset)
      .execute();
    const total =
      rows.length > 0
        ? Number(rows[0].total)
        : offset === 0
          ? 0
          : (await this.listPipelineFailures({ limit: 1 })).total;
    const sessions = rows.map((r) => ({
      sourceSessionId: r.source_session_id,
      coachId: r.coach_id,
      title: r.title,
      sessionDate: r.date,
      sessionStartedAt: r.session_started_at,
      state: r.state,
      attempts: r.retry_count,
      reportId: r.report_id,
      reason:
        r.state === "upload_failed"
          ? r.hold_reason
          : r.coach_id === null
            ? r.leader_cue === "none"
              ? "unattributed: the transcript did not name which of the rotating class's leaders led"
              : "unattributed: no leader matched the session title"
            : r.state === "delivered" && r.skipped_leader
              ? `delivered, but not emailed to ${r.skipped_leader}: ${r.skipped_group ? "a rotating class's group address, not the leader's own" : "placeholder address"}`
              : r.hold_reason ??
                (r.release_required ? REATTRIBUTED_HOLD : null),
      holdKind: (r.hold_kind ??
        (r.release_required ? "reattributed" : null)) as HoldKind | null,
      ...(r.hold_kind === "cold-recall"
        ? { coldRecall: coldRecallInFeedback(r.cold_recall_feedback) }
        : {}),
      action:
        r.state === "upload_failed"
          ? null
          : r.coach_id === null
            ? ("attribute" as const)
            : r.parallel_run
              ? r.state === "scoring_failed"
                ? ("requeue" as const)
                : null
              : r.state === "delivered"
                ? null
                : r.state === "scored" || r.release_required
                  ? ("release" as const)
                  : r.state === "delivery_pending"
                    ? null
                    : ("requeue" as const),
      parallelRun: r.parallel_run,
      updatedAt: new Date(r.updated_at as unknown as string),
    }));
    return { total, sessions };
  }

  async releaseHeldReport(reportId: string): Promise<{
    delivered: boolean;
    refusal?: string;
    violations?: string[];
    coldRecall?: string[];
    skipped?: string[];
  }> {
    const held = await this.db
      .getOrCreateConnection()
      .selectFrom("coach_intake_sessions")
      .select(["parallel_run", "coach_id"])
      .where("report_id", "=", reportId)
      .where(releasable)
      .executeTakeFirst();
    if (!held) return { delivered: false, refusal: "not-held" };
    if (held.parallel_run)
      return { delivered: false, refusal: "parallel-run-session" };
    if (!this.notification) return { delivered: false, refusal: "no-mailer" };
    await this.db
      .getOrCreateConnection()
      .updateTable("coach_intake_sessions")
      .set({
        release_required: false,
        retry_count: sql`CASE WHEN state = 'delivery_failed' THEN 0 ELSE retry_count END`,
        state: sql`CASE WHEN state = 'delivery_failed' THEN 'delivery_pending' ELSE state END`,
        hold_reason: sql`CASE WHEN hold_kind = 'scoring-version' THEN NULL ELSE hold_reason END`,
        hold_kind: sql`CASE WHEN hold_kind = 'scoring-version' THEN NULL ELSE hold_kind END`,
      })
      .where("report_id", "=", reportId)
      .where(releasable)
      .execute();
    const delivery = new CoachDeliveryService(this.db, this.notification);
    const result = await delivery.deliver({
      reportId,
      evidence: await storedEvidence(this.db, reportId),
    });
    if (result.delivered && held.coach_id)
      await releaseDeliveredVersions(this.db, held.coach_id);
    return {
      delivered: result.delivered,
      ...(result.refusal ? { refusal: result.refusal } : {}),
      ...(result.violations
        ? { violations: result.violations.map((v) => v.rule) }
        : {}),
      ...(result.coldRecall ? { coldRecall: result.coldRecall } : {}),
      ...(result.skipped?.length ? { skipped: result.skipped } : {}),
    };
  }

  async requeuePipelineFailure(
    sourceSessionId: string,
  ): Promise<boolean | "parallel-run-session"> {
    const conn = this.db.getOrCreateConnection();
    const parked = await conn
      .selectFrom("coach_intake_sessions")
      .select("parallel_run")
      .where("source_session_id", "=", sourceSessionId)
      .where("state", "=", "delivery_failed")
      .executeTakeFirst();
    if (parked?.parallel_run) return "parallel-run-session";
    const requeued = await conn
      .updateTable("coach_intake_sessions")
      .set({
        state: sql`CASE WHEN state = 'scoring_failed' THEN 'retained' ELSE 'delivery_pending' END`,
        retry_count: 0,
        send_unconfirmed: sql`send_unconfirmed OR cardinality(attempted_to) > 0`,
        attempted_to: sql`ARRAY[]::text[]`,
        hold_reason: null,
        hold_kind: null,
        updated_at: sql`NOW()`,
      })
      .where("source_session_id", "=", sourceSessionId)
      .where(requeuable)
      .executeTakeFirst();
    return Number(requeued.numUpdatedRows ?? 0) > 0;
  }

