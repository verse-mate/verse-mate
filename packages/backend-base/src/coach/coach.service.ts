  /** Every leader's classes with owner identity resolved (admin export). The
   *  Fireflies operator reads this to configure which meeting links the bot
   *  auto-joins. Owner name comes from the coaching roster when the account is
   *  a known leader; otherwise it falls back to the account's email. */
  async listAllClasses(): Promise<AdminCoachClass[]> {
    const rows = await this.coachRepository.listAllClasses();
    // Resolve each distinct user_id once → email → roster record.
    const emailCache = new Map<string, string | null>();
    const out: AdminCoachClass[] = [];
    for (const row of rows) {
      if (!emailCache.has(row.userId)) {
        emailCache.set(row.userId, await this.emailFor(row.userId));
      }
      const email = emailCache.get(row.userId) ?? null;
      const record = email ? await this.resolveByEmail(email) : null;
      out.push({
        id: row.id,
        name: row.name,
        classDate: row.classDate,
        recurrence: row.recurrence,
        zoomLink: row.zoomLink,
        leader: {
          id: record?.id ?? null,
          name: record?.name ?? email ?? "Unknown",
          email: email ?? "",
        },
      });
    }
    return out;
  }

  /** Derive the chart series from a coach's reports. Pure, exported shape
   *  matches the web client's CoachTrends. */
  static buildTrends(reports: CoachReport[]): CoachTrends {
    const chrono = [...reports].sort((a, b) => (a.date < b.date ? -1 : 1));

    const scoreSeries = chrono.map((r) => ({
      date: r.date,
      dateLabel: r.dateLabel,
      session: r.session,
      score: r.score,
      status: r.status,
      reportId: r.id,
    }));

    const clusterSeries: TrendRow[] = chrono.map((r) => {
      const row: TrendRow = { date: r.date, dateLabel: r.dateLabel };
      for (const c of r.clusters) row[c.name] = c.contribution;
      return row;
    });

    const dimensionSeries: TrendRow[] = chrono.map((r) => {
      const row: TrendRow = { date: r.date, dateLabel: r.dateLabel };
      for (const d of r.dimensions) row[d.name] = d.score;
      return row;
    });

    let delta: CoachTrends["delta"] = null;
    if (chrono.length >= 2) {
      const latest = chrono[chrono.length - 1];
      const prev = chrono[chrono.length - 2];
      delta = {
        score: Math.round((latest.score - prev.score) * 100) / 100,
        from: prev.score,
        to: latest.score,
        fromLabel: prev.dateLabel,
        toLabel: latest.dateLabel,
      };
    }

    return { scoreSeries, clusterSeries, dimensionSeries, delta };
  }
