  async listPipelineFailures(
    page: { limit?: number; offset?: number } = {},
  ): Promise<{
    total: number;
    sessions: Array<{
      sourceSessionId: string;
      coachId: string | null;
      title: string;
      sessionDate: string;
      state: string;
      attempts: number;
      reportId: string | null;
      reason: string | null;
      action: "release" | "requeue" | "attribute" | null;
      updatedAt: Date;
    }>;
  }> {
    const limit = Math.min(
      Math.max(1, page.limit ?? PIPELINE_FAILURES_PAGE),
      PIPELINE_FAILURES_MAX,
    );
    const offset = Math.max(0, page.offset ?? 0);
    const rows = await this.db
      .getOrCreateConnection()
      .selectFrom("coach_intake_sessions")
      .select([
        "source_session_id",
        "coach_id",
        "title",
        "state",
        "retry_count",
        "report_id",
        "hold_reason",
        "release_required",
        "updated_at",
      ])
      .select(sql<string>`to_char(session_date, 'YYYY-MM-DD')`.as("date"))
      .select(SKIPPED_LEADER_ADDRESS.as("skipped_leader"))
      .select(sql<string>`count(*) OVER ()`.as("total"))
      .where((eb) =>
        eb.or([
          eb("state", "in", [
            "scoring_failed",
            "delivery_pending",
            "delivery_failed",
          ]),
          eb.and([
            eb("state", "=", "scored"),
            eb.or([
              eb("hold_reason", "is not", null),
              eb("release_required", "=", true),
            ]),
          ]),
          eb("coach_id", "is", null),
          eb.and([
            eb("state", "=", "delivered"),
            eb(SKIPPED_LEADER_ADDRESS, "is not", null),
          ]),
        ]),
      )
      .orderBy("updated_at", "desc")
      .orderBy("source_session_id")
      .limit(limit)
      .offset(offset)
      .execute();
    const total =
      rows.length > 0
        ? Number(rows[0].total)
        : offset === 0
          ? 0
          : (await this.listPipelineFailures({ limit: 1 })).total;
    const sessions = rows.map((r) => ({
      sourceSessionId: r.source_session_id,
      coachId: r.coach_id,
      title: r.title,
      sessionDate: r.date,
      state: r.state,
      attempts: r.retry_count,
      reportId: r.report_id,
      reason:
        r.coach_id === null
          ? "unattributed: no leader matched the session title"
          : r.state === "delivered" && r.skipped_leader
            ? `delivered, but not emailed to ${r.skipped_leader}: placeholder address`
            : r.hold_reason ?? (r.release_required ? REATTRIBUTED_HOLD : null),
      action:
        r.coach_id === null
          ? ("attribute" as const)
          : r.state === "delivered"
            ? null
            : r.state === "scored" || r.release_required
              ? ("release" as const)
              : r.state === "delivery_pending"
                ? null
                : ("requeue" as const),
      updatedAt: new Date(r.updated_at as unknown as string),
    }));
    return { total, sessions };
  }

  async releaseHeldReport(reportId: string): Promise<{
    delivered: boolean;
    refusal?: string;
    violations?: string[];
    shortfalls?: string[];
    coldRecall?: string[];
    skipped?: string[];
  }> {
    const releasable = (
      eb: ExpressionBuilder<Database, "coach_intake_sessions">,
    ) =>
      eb.and([
        eb("report_id", "=", reportId),
        eb.or([
          eb("state", "=", "scored"),
          eb.and([
            eb("release_required", "=", true),
            eb("state", "in", ["delivery_pending", "delivery_failed"]),
          ]),
        ]),
      ]);
    const held = await this.db
      .getOrCreateConnection()
      .selectFrom("coach_intake_sessions")
      .select("source_session_id")
      .where(releasable)
      .executeTakeFirst();
    if (!held) return { delivered: false, refusal: "not-held" };
    if (!this.notification) return { delivered: false, refusal: "no-mailer" };
    await this.db
      .getOrCreateConnection()
      .updateTable("coach_intake_sessions")
      .set({
        release_required: false,
        retry_count: sql`CASE WHEN state = 'delivery_failed' THEN 0 ELSE retry_count END`,
        state: sql`CASE WHEN state = 'delivery_failed' THEN 'delivery_pending' ELSE state END`,
      })
      .where(releasable)
      .execute();
    const { CoachDeliveryService } = await import("./coach-delivery.service");
    const { storedEvidence } = await import("./coach-pipeline.service");
    const result = await new CoachDeliveryService(
      this.db,
      this.notification,
    ).deliver({ reportId, evidence: await storedEvidence(this.db, reportId) });
    return {
      delivered: result.delivered,
      ...(result.refusal ? { refusal: result.refusal } : {}),
      ...(result.violations
        ? { violations: result.violations.map((v) => v.rule) }
        : {}),
      ...(result.shortfalls ? { shortfalls: result.shortfalls } : {}),
      ...(result.coldRecall ? { coldRecall: result.coldRecall } : {}),
      ...(result.skipped?.length ? { skipped: result.skipped } : {}),
    };
  }

  async requeuePipelineFailure(sourceSessionId: string): Promise<boolean> {
    const requeued = await this.db
      .getOrCreateConnection()
      .updateTable("coach_intake_sessions")
      .set({
        state: sql`CASE WHEN state = 'scoring_failed' THEN 'retained' ELSE 'delivery_pending' END`,
        retry_count: 0,
        hold_reason: null,
        updated_at: sql`NOW()`,
      })
      .where("source_session_id", "=", sourceSessionId)
      .where("state", "in", ["scoring_failed", "delivery_failed"])
      .executeTakeFirst();
    return Number(requeued.numUpdatedRows ?? 0) > 0;
  }

