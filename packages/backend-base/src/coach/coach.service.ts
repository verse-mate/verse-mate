  private static mean(nums: number[]): number | null {
    if (nums.length === 0) return null;
    return (
      Math.round((nums.reduce((a, b) => a + b, 0) / nums.length) * 10) / 10
    );
  }

  /** Highest status band whose min the score meets (bands are stored desc). */
  private static statusFor(score: number | null): {
    label: string;
    emoji: string;
  } {
    if (score === null) return { label: "", emoji: "" };
    const band = STATUS_BANDS.find((b) => score >= b.min);
    return band
      ? { label: band.label, emoji: band.emoji }
      : { label: "", emoji: "" };
  }

  /** "2026-07" → "2026-06". */
  private static prevMonth(month: string): string {
    const [y, m] = month.split("-").map(Number);
    if (!y || !m) return month;
    const d = m === 1 ? { y: y - 1, m: 12 } : { y, m: m - 1 };
    return `${d.y}-${String(d.m).padStart(2, "0")}`;
  }

  /** "2026-07" → "July 2026". */
  private static monthLabel(month: string): string {
    const names = [
      "January",
      "February",
      "March",
      "April",
      "May",
      "June",
      "July",
      "August",
      "September",
      "October",
      "November",
      "December",
    ];
    const [y, m] = month.split("-").map(Number);
    if (!y || !m || m < 1 || m > 12) return month;
    return `${names[m - 1]} ${y}`;
  }

