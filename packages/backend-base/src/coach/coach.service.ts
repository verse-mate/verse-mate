  // ─── Publish (ingest) ────────────────────────────────────────────────────

  /**
   * Ingest published reports into the store (change: coach-reports-store).
   *
   * The store is the sole assigner of report identity: an incoming report is
   * matched on the title-free natural key (coach + session date), so a re-title
   * updates the existing row and KEEPS its id, overlay notes/recording links
   * and already-delivered `?s=<id>` links stay valid. The response carries each
   * report's assigned id so the publisher can build links without deriving one.
   *
   * Guards the corpus against a stale writer: when `expectedCounts` names a
   * leader whose claimed total is lower than what the store already holds FOR
   * THAT LEADER, the write is refused rather than allowed to shrink live data.
   *
   * Per leader, not global. Compared against the whole store, one leader's
   * incremental session looked like a corpus of 1 replacing a corpus of N, so
   * every valid incremental write was refused, and the guard is only meaningful
   * per leader anyway, since a write naming one leader says nothing about
   * another's history. A leader absent from `expectedCounts` is not judged.
   */
  async ingestReports(input: {
    reports: Array<{
      coachId: string;
      date: string;
      /** The provider's session identifier, part of the row's natural key. */
      sourceSessionId: string;
      id?: string;
      summary: Record<string, unknown>;
      metrics: Record<string, unknown>;
      body: Record<string, unknown>;
    }>;
    generatedAt?: string | null;
    /**
     * The writer's claimed TOTAL number of reports per leader, keyed by coach
     * id. A leader not named here is not judged by this batch.
     */
    expectedCounts?: Record<string, number> | null;
  }): Promise<{
    accepted: Array<{
      id: string;
      coachId: string;
      date: string;
      created: boolean;
    }>;
    version: string;
    reportCount: number;
  }> {
    for (const [coachId, expected] of Object.entries(
      input.expectedCounts ?? {},
    )) {
      if (typeof expected !== "number") continue;
      const stored = await this.reportsRepository.countForCoach(coachId, {
        includeHeld: true,
      });
      if (expected < stored) {
        throw new ConflictError(
          `Write refused for ${coachId}: the writer reports ${expected} sessions but the store holds ${stored} for that leader, refusing to shrink the live corpus`,
        );
      }
    }

    // Validate the WHOLE batch before writing anything, so a bad report at
    // position k cannot leave reports 1..k-1 committed.
    for (const report of input.reports) {
      if (!report.coachId || !report.date || !report.sourceSessionId) {
        throw new ValidationError(
          "Each report needs a coachId, a date and a sourceSessionId",
        );
      }
      if (!/^\d{4}-\d{2}-\d{2}$/.test(report.date)) {
        throw new ValidationError(
          `Report date must be yyyy-mm-dd (got "${report.date}" for ${report.coachId})`,
        );
      }
      // The read path serves ReportSchema, which REQUIRES these fields. Without
      // this check a publisher that renames one field gets a 200, and the
      // malformed row then breaks the leader's ENTIRE report list (the array
      // response fails validation as a whole), with no repair endpoint.
      const assembled = {
        ...report.summary,
        ...report.metrics,
        ...report.body,
      } as Record<string, unknown>;
      const missing = CoachService.REQUIRED_REPORT_FIELDS.filter(
        (f) => assembled[f] === undefined,
      );
      if (missing.length > 0) {
        throw new ValidationError(
          `Report ${report.coachId} ${report.date} is missing required field(s): ${missing.join(", ")}`,
        );
      }
    }

    // ONE transaction for the whole batch. Without it a database error at
    // report k left reports 1..k-1 committed AND skipped the provenance bump,
    // so the store held rows that `coach_dataset_meta` did not account for and
    // no caller could tell a partial publish from a complete one. Rolling back
    // also leaves the batch intact for the caller to retry.
    const { accepted, meta } = await this.reportsRepository.transaction(
      async (writer) => {
        const written: Array<{
          id: string;
          coachId: string;
          date: string;
          created: boolean;
        }> = [];
        for (const report of input.reports) {
          written.push(
            await this.reportsRepository.upsert(
              {
                id:
                  report.id ||
                  CoachService.mintReportId(
                    report.coachId,
                    report.date,
                    report.sourceSessionId,
                  ),
                coach_id: report.coachId,
                session_date: report.date,
                source_session_id: report.sourceSessionId,
                legacy_ids: [],
                summary: report.summary ?? {},
                metrics: report.metrics ?? {},
                body: report.body ?? {},
              },
              writer,
            ),
          );
        }
        return {
          accepted: written,
          meta: await this.reportsRepository.bumpMeta(
            input.generatedAt ?? null,
            writer,
          ),
        };
      },
    );

    return {
      accepted,
      version: meta.version,
      reportCount: meta.reportCount,
    };
  }

  /**
   * Fields the read contract (ReportSchema) requires. An ingest that omits any
   * of them is rejected at the write boundary rather than poisoning the read.
   */
  private static readonly REQUIRED_REPORT_FIELDS = [
    "dateLabel",
    "session",
    "topic",
    "duration",
    "attendees",
    "newcomers",
    "score",
    "base",
    "newcomerBonus",
    "sizeBonus",
    "status",
    "statusEmoji",
    "clusters",
    "dimensions",
    "bigIdeas",
    "feedback",
    // docUrl / pdfUrl are NOT here: the Drive stage is not ported, so nothing
    // can supply them and requiring them would move the same wall one step
    // earlier, to the write boundary.
  ];

  /**
   * Opaque id for a report the store has not seen before. DETERMINISTIC in the
   * natural key, not random: an id minted freshly on every publish lands in
   * `legacy_ids` each time a retry turns the insert into an update, so the
   * array grows without bound. Derived from the source session id, which is
   * opaque provider output, never the session title, so it carries no title
   * and re-minting for the same session reproduces the same value.
   */
  private static mintReportId(
    coachId: string,
    date: string,
    sourceSessionId: string,
  ): string {
    const digest = createHash("sha256")
      .update(`${coachId}\u0000${date}\u0000${sourceSessionId}`)
      .digest("hex")
      .slice(0, 8);
    return `${coachId}-${date}-${digest}`;
  }

