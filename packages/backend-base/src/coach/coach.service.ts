  // ─── Monthly cross-leader analysis ───────────────────────────────────────

  /** Program-wide + per-leader rollup for one YYYY-MM month, computed live
   *  from the dataset (current v3 weighted model). Mirrors the coaching
   *  pipeline's monthly summary. */
  async getMonthly(month: string): Promise<CoachMonthly> {
    const records = await this.recordsWithStoreReports();
    const prev = CoachService.prevMonth(month);

    // Canonical n→name map for the 12-dimension heatmap columns, plus the set
    // of months that actually have reports (for the picker).
    const dimNames = new Map<number, string>();
    const monthSet = new Set<string>();
    for (const c of records)
      for (const r of c.reports) {
        monthSet.add(r.date.slice(0, 7));
        for (const d of r.dimensions)
          if (!dimNames.has(d.n)) dimNames.set(d.n, d.name);
      }
    const dimList = [...dimNames.entries()].sort((a, b) => a[0] - b[0]);
    const availableMonths = [...monthSet].sort((a, b) => (a < b ? 1 : -1));

    const leaders: MonthlyLeader[] = [];
    let programSessions = 0;
    let programNewcomers = 0;
    const monthScores: number[] = [];
    const prevScores: number[] = [];
    const clusterSums = new Map<string, { sum: number; n: number }>();

    for (const c of records) {
      const inMonth = c.reports.filter((r) => r.date.startsWith(month));
      const inPrev = c.reports.filter((r) => r.date.startsWith(prev));
      if (inMonth.length === 0) continue;

      const avg = CoachService.mean(inMonth.map((r) => r.score));
      const prevAvg = inPrev.length
        ? CoachService.mean(inPrev.map((r) => r.score))
        : null;
      const band = CoachService.statusFor(avg);

      leaders.push({
        id: c.id,
        name: c.name,
        group: c.group,
        sessions: inMonth.length,
        avgScore: avg,
        status: band.label,
        statusEmoji: band.emoji,
        dimensions: dimList.map(([n, name]) => ({
          n,
          name,
          avg: CoachService.mean(
            inMonth
              .flatMap((r) => r.dimensions.filter((d) => d.n === n))
              .map((d) => d.score)
              .filter((s): s is number => s !== null),
          ),
        })),
        delta:
          avg !== null && prevAvg !== null
            ? Math.round((avg - prevAvg) * 10) / 10
            : null,
      });

      programSessions += inMonth.length;
      for (const r of inMonth) {
        programNewcomers += r.newcomers;
        monthScores.push(r.score);
        for (const cl of r.clusters) {
          if (cl.scorePct === null) continue;
          const acc = clusterSums.get(cl.name) ?? { sum: 0, n: 0 };
          acc.sum += cl.scorePct;
          acc.n += 1;
          clusterSums.set(cl.name, acc);
        }
      }
      for (const r of inPrev) prevScores.push(r.score);
    }

    leaders.sort((a, b) => (b.avgScore ?? -1) - (a.avgScore ?? -1));

    const programAvg = CoachService.mean(monthScores);
    const prevProgramAvg = prevScores.length
      ? CoachService.mean(prevScores)
      : null;

    return {
      month,
      monthLabel: CoachService.monthLabel(month),
      program: {
        sessions: programSessions,
        activeLeaders: leaders.length,
        newcomers: programNewcomers,
        avgScore: programAvg,
        clusters: CLUSTERS.map((cl) => {
          const acc = clusterSums.get(cl.name);
          return {
            name: cl.name,
            weight: cl.weight,
            avg: acc?.n ? Math.round((acc.sum / acc.n) * 10) / 10 : null,
          };
        }),
        delta:
          programAvg !== null && prevProgramAvg !== null
            ? Math.round((programAvg - prevProgramAvg) * 10) / 10
            : null,
      },
      leaders,
      availableMonths,
      narrative: await this.narrativeFor(month),
    };
  }

