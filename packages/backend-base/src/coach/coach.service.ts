  /** Overlay admin-editable state (recording link + notes) onto a coach's
   *  reports. Returns fresh objects, never mutates the bundled dataset. */
  private async overlayReports(
    coachId: string,
    reports: CoachReport[],
    fallbackRecordingUrl = "",
  ): Promise<CoachReport[]> {
    if (reports.length === 0) return [];
    const [recMap, noteRows] = await Promise.all([
      this.coachRepository.getRecordingLinksForCoach(coachId),
      this.coachRepository.listNotes(coachId),
    ]);
    const notesByReport = new Map<string, CoachNoteRow[]>();
    for (const n of noteRows) {
      const list = notesByReport.get(n.reportId) ?? [];
      list.push(n);
      notesByReport.set(n.reportId, list);
    }
    return reports.map((r) => {
      // An explicit admin value (including an explicit clear to "") wins;
      // otherwise fall back to any bundled URL, then to the leader's saved
      // meeting link so every session auto-carries a recording link.
      const explicit = recMap[r.id];
      const recordingUrl =
        explicit !== undefined
          ? explicit
          : r.recordingUrl || fallbackRecordingUrl || "";
      return {
        ...r,
        recordingUrl,
        attachedRecordingUrl: explicit ? explicit : null,
        notes: (notesByReport.get(r.id) ?? []).map(CoachService.toNoteView),
      };
    });
  }

  private static toNoteView(row: CoachNoteRow): CoachNoteView {
    return {
      id: row.id,
      body: row.body,
      createdAt: row.createdAt,
      emailed: row.emailed,
    };
  }

