  async addLeader(
    adminUserId: string,
    input: { email: string; name?: string; group?: string; coachName?: string },
  ): Promise<
    | { ok: true; coach: CoachSummary }
    | { ok: false; reason: "duplicate" }
    | { ok: false; reason: "no-slug" }
    | { ok: false; reason: "slug-taken"; slug: string }
  > {
    const email = input.email.trim().toLowerCase();
    if (await this.resolveByEmail(email))
      return { ok: false, reason: "duplicate" };

    const name = input.name?.trim() || CoachService.nameFromEmail(email);
    const slug = leaderSlug(name);
    if (!slug) return { ok: false, reason: "no-slug" };
    if (
      this.findById(slug) ||
      (await this.coachRepository.findLeaderBySlug(slug))
    )
      return { ok: false, reason: "slug-taken", slug };
    let row: AddedLeaderRow;
    try {
      row = await this.coachRepository.addLeader({
        slug,
        email,
        name,
        group: input.group?.trim() ?? "",
        coachName: input.coachName?.trim() ?? "",
        invitedBy: adminUserId,
      });
    } catch (error) {
      if ((error as { code?: string }).code !== "23505") throw error;
      return (await this.coachRepository.findAddedLeaderByEmail(email))
        ? { ok: false, reason: "duplicate" }
        : { ok: false, reason: "slug-taken", slug };
    }

    const mailer = isPlaceholderAddress(email) ? undefined : this.notification;
    try {
      const invitedBy = await this.displayNameFor(adminUserId);
      const portalUrl = `${process.env.APP_URL ?? ""}/coach`;
      await mailer?.sendEmail({
        to: { email, name },
        subject: "You've been added to VerseMate Coaching",
        text: `You've been added to the VerseMate coaching portal. Sign in at ${portalUrl} with this email to see your dashboard.`,
        html: render(CoachInvite({ name, invitedBy, portalUrl })),
      });
    } catch (err) {
      console.log("[CoachService] invite email failed:", err);
    }

    return {
      ok: true,
      coach: {
        id: slug,
        name,
        group: row.group_name,
        coachName: row.coach_name,
        sessionCount: 0,
        latest: null,
      },
    };
  }

