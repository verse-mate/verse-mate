  /** Persist a coaching note on a session, email it to the leader, and return
   *  the saved note. null → unknown coach/session. */
  async addNote(
    coachId: string,
    reportId: string,
    authorUserId: string | null,
    body: string,
  ): Promise<CoachNoteView | "held" | null> {
    const record = await this.resolveById(coachId);
    if (!record) return null;
    const canonical = await this.canonicalReportId(coachId, reportId, record);
    if (!canonical) return null;
    const stored = await this.db
      .getOrCreateConnection()
      .selectFrom("coach_reports")
      .select("held")
      .where("id", "=", canonical)
      .executeTakeFirst();
    if (stored?.held) return "held";
    const report =
      (await this.getReportDetail(coachId, canonical, "admin")) ??
      record.reports.find((r) => r.id === canonical);
    if (!report) return null;

    // Email the leader first; persist with the actual delivery outcome so the
    // note is never lost even if the mailer throws.
    let emailed = false;
    try {
      if (
        this.notification &&
        record.email &&
        !isPlaceholderAddress(record.email)
      ) {
        const portalUrl = `${process.env.APP_URL ?? ""}/coach`;
        // Read the result. Mailgun failures are RETURNED, not thrown (that is
        // the whole point of SendResult), so the surrounding catch never fires
        // for a real send failure, and this recorded `emailed: true` for a 401
        // or a 500. The admin then saw the note marked as emailed and believed
        // the leader had been notified.
        const sent = (await this.notification.sendEmail({
          to: { email: record.email, name: record.name },
          subject: `Coaching note — ${report.session}`,
          text: body,
          html: render(
            CoachNote({
              name: record.name,
              sessionLabel: `${report.session} — ${report.dateLabel}`,
              body,
              portalUrl,
            }),
          ),
        })) as CoachSendResult | undefined;
        emailed = sent?.delivered === true;
      }
    } catch (err) {
      console.log("[CoachService] note email failed:", err);
    }

    const saved = await this.coachRepository.addNote({
      coachId,
      // persist the canonical id so the note attaches to the report's identity
      reportId: canonical,
      authorUserId,
      body,
      emailed,
    });
    return CoachService.toNoteView(saved);
  }

