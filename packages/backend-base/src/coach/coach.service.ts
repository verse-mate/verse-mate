  /** Turn an admin-added leader row into a roster record (no reports yet). */
  private static syntheticRecord(row: AddedLeaderRow): CoachRecord {
    return {
      // The SLUG, not the row's uuid. Every overlay, coach_reports,
      // coach_notes, coach_recording_links, keys on the slug, so a record
      // carrying the uuid joins to nothing and the leader sees an empty
      // history. Harmless while the bundle supplied slug-keyed records for
      // real leaders; after task 7.1 deletes it, EVERY leader resolves through
      // here, so the uuid would empty every history at once.
      id: row.slug ?? row.id,
      name: row.name || CoachService.nameFromEmail(row.email),
      email: row.email,
      group: row.group_name,
      coachName: row.coach_name,
      isCoach: true,
      zoomLink: "",
      reports: [],
    };
  }

  /** "jeff.ward@x.com" → "Jeff Ward". Best-effort display name for a leader
   *  added by email only. */
  private static nameFromEmail(email: string): string {
    const local = email.split("@")[0] ?? email;
    return (
      local
        .split(/[._-]+/)
        .filter(Boolean)
        .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
        .join(" ") || email
    );
  }

  private async resolveByEmail(email: string): Promise<CoachRecord | null> {
    const row = await this.coachRepository.findAddedLeaderByEmail(email);
    const bundled = row?.slug
      ? this.findById(row.slug)
      : this.findByEmail(email);
    if (bundled) {
      if (row) return { ...bundled, email: row.email };
      if (await this.coachRepository.findLeaderBySlug(bundled.id)) return null;
      return bundled;
    }
    return row ? CoachService.syntheticRecord(row) : null;
  }

  private async resolveById(coachId: string): Promise<CoachRecord | null> {
    const bundled = this.findById(coachId);
    if (bundled) {
      const row = await this.coachRepository.findLeaderBySlug(coachId);
      return row ? { ...bundled, email: row.email } : bundled;
    }
    const added = (await this.coachRepository.listAddedLeaders()).find(
      (r) => (r.slug ?? r.id) === coachId,
    );
    return added ? CoachService.syntheticRecord(added) : null;
  }

  private async allRecords(): Promise<CoachRecord[]> {
    const added = await this.coachRepository.listAddedLeaders();
    const bySlug = new Map(added.map((a) => [a.slug, a]));
    const bundled = this.bundle.coaches.map((c) => {
      const row = bySlug.get(c.id);
      return row ? { ...c, email: row.email } : c;
    });
    const bundledEmails = new Set(bundled.map((c) => c.email));
    const synthetic = added
      .filter((a) => !bundledEmails.has(a.email))
      .map(CoachService.syntheticRecord);
    return [...bundled, ...synthetic];
  }

  async updateLeaderEmail(
    slug: string,
    address: string,
    options: { byUserId?: string | null; confirm?: boolean } = {},
  ): Promise<
    | { ok: true; email: string; noticeSent: boolean }
    | { ok: false; refusal: "unknown-leader" | "taken" | "confirm-required" }
  > {
    const email = address.trim().toLowerCase();
    const holder = await this.resolveByEmail(email);
    if (holder && holder.id !== slug) return { ok: false, refusal: "taken" };
    const change = await this.db
      .getOrCreateConnection()
      .transaction()
      .execute(async (trx) => {
        const leader = await trx
          .selectFrom("coach_leaders")
          .select(["email", "name", "is_benchmark"])
          .where("slug", "=", slug)
          .forUpdate()
          .executeTakeFirst();
        if (!leader) return { refusal: "unknown-leader" as const };
        if (leader.is_benchmark && options.confirm !== true)
          return { refusal: "confirm-required" as const };
        if (leader.email === email)
          return { refusal: null, previous: null, name: leader.name };
        await trx
          .updateTable("coach_leaders")
          .set({ email })
          .where("slug", "=", slug)
          .execute();
        await trx
          .insertInto("coach_leader_email_changes")
          .values({
            slug,
            previous_email: leader.email,
            new_email: email,
            changed_by: options.byUserId ?? null,
          })
          .execute();
        return { refusal: null, previous: leader.email, name: leader.name };
      });
    if (change.refusal) return { ok: false, refusal: change.refusal };
    const noticeSent = change.previous
      ? await this.sendAddressChangedNotice(change.previous, change.name)
      : false;
    return { ok: true, email, noticeSent };
  }

  private async sendAddressChangedNotice(
    previous: string,
    name: string,
  ): Promise<boolean> {
    if (
      !this.notification ||
      !coachPipelineLive() ||
      isPlaceholderAddress(previous)
    )
      return false;
    try {
      const sent = (await this.notification.sendEmail({
        to: { email: previous, name },
        replyTo: { name: COACH_REPLY_TO_NAME, email: COACH_REPLY_TO_EMAIL },
        subject: "Your VerseMate coaching address was changed",
        text: `A program admin changed the email address your VerseMate coaching reports go to. Reports and notes are no longer sent to this address. If you did not expect this, reply to this email or write to ${COACH_REPLY_TO_EMAIL}.`,
        html: render(
          CoachAddressChanged({ name, replyTo: COACH_REPLY_TO_EMAIL }),
        ),
      })) as CoachSendResult | undefined;
      return sent?.delivered === true;
    } catch (err) {
      console.log("[CoachService] address change notice failed:", err);
      return false;
    }
  }

  /** Overlay admin-editable state (recording link + notes) onto a coach's
   *  reports. Returns fresh objects, never mutates the bundled dataset. */
  private async overlayReports(
    coachId: string,
    reports: CoachReport[],
    fallbackRecordingUrl = "",
  ): Promise<CoachReport[]> {
    if (reports.length === 0) return [];
    const [recMap, noteRows] = await Promise.all([
      this.coachRepository.getRecordingLinksForCoach(coachId),
      this.coachRepository.listNotes(coachId),
    ]);
    const notesByReport = new Map<string, CoachNoteRow[]>();
    for (const n of noteRows) {
      const list = notesByReport.get(n.reportId) ?? [];
      list.push(n);
      notesByReport.set(n.reportId, list);
    }
    return reports.map((r) => {
      // An explicit admin value (including an explicit clear to "") wins;
      // otherwise fall back to any bundled URL, then to the leader's saved
      // meeting link so every session auto-carries a recording link.
      const explicit = recMap[r.id];
      const recordingUrl =
        explicit !== undefined
          ? explicit
          : r.recordingUrl || fallbackRecordingUrl || "";
      return {
        ...r,
        recordingUrl,
        attachedRecordingUrl: explicit ? explicit : null,
        notes: (notesByReport.get(r.id) ?? []).map(CoachService.toNoteView),
      };
    });
  }

  private static toNoteView(row: CoachNoteRow): CoachNoteView {
    return {
      id: row.id,
      body: row.body,
      createdAt: row.createdAt,
      emailed: row.emailed,
    };
  }

